_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PDF_PATH = os.path.join(_ROOT, 'cache', 'curriculum', 'curr.pdf')
_TEXT = {}


def _pdf_pages():
    """PDF 를 (없으면) 받아 pypdf 로 쪽별 글자를 돌려준다. pypdf 가 없으면 None."""
    if 'pages' in _TEXT:
        return _TEXT['pages']
    try:
        import pypdf
    except ImportError:
        print('curriculum: pypdf 가 없어 원문 검사를 건너뛴다(pip install pypdf)', file=sys.stderr)
        _TEXT['pages'] = None
        return None
    if not os.path.exists(PDF_PATH):
        os.makedirs(os.path.dirname(PDF_PATH), exist_ok=True)
        req = urllib.request.Request(PDF_URL, headers={'User-Agent': 'Mozilla/5.0 (compatible; hongikon-ask-crawler; +https://hongikon.com)'})
        data = urllib.request.urlopen(req, timeout=60).read()
        if not data.startswith(b'%PDF'):
            raise RuntimeError('curriculum: PDF 가 아닌 응답')
        open(PDF_PATH, 'wb').write(data)
    reader = pypdf.PdfReader(PDF_PATH)
    _TEXT['pages'] = [re.sub(r'\s+', '', p.extract_text(extraction_mode='layout') or '') for p in reader.pages]
    return _TEXT['pages']


def _tokens(line):
    # 낱말(한글·영문 덩어리)과 숫자 덩어리. 쪽 글자에서 순서는 뒤섞여도 덩어리 자체는 그대로 나온다.
    # 한글과 영문이 붙은 곳('R프로그래밍', '2set를')은 PDF 에서 따로 나올 수 있어 나눠서 본다.
    return [t for t in re.findall(r'[가-힣]+|[A-Za-z]+|\d+', line) if len(t) >= 2 or t.isdigit()]


def _verified(page_text, line):
    norm = page_text.replace('Ⅰ', 'I').replace('Ⅱ', 'II')
    return [t for t in _tokens(line) if t not in norm]


def postprocess(key, page, raw):
    bands = BANDS.get(key)
    if not bands:
        return page
    pages = _pdf_pages()
    sections = []
    for pno, title, lines in bands:
        kept = []
        for line in lines:
            if pages is not None:
                missing = _verified(pages[pno - 1], line)
                if missing:
                    print(f'curriculum: {key} p{pno} 원문에 없는 낱말 {missing[:5]} → 줄 버림: {line[:40]}', file=sys.stderr)
                    continue
            kept.append(line)
        if kept:
            sections.append({'title': title, 'items': kept, 'ordered': False})
    return {'title': TITLES.get(key, page.get('title', '')), 'sections': sections}


