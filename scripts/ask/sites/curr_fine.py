def _missing(page_text, line):
    # curriculum._verified 로 먼저 보고, 거기서 빠진 낱말만 쪽 글자에서 기호·숫자를 걷어낸 글자에 다시 찾는다.
    # 각주처럼 여러 줄에 걸친 문장은 줄바꿈 자리에 숫자·괄호가 끼어 낱말이 갈라져 나오기 때문이다('하,…며', '4학…점에').
    # 숫자 덩어리는 걷어내지 않은 원래 쪽 글자에 있어야 한다.
    missing = _verified(page_text, line)
    letters = re.sub(r'[^가-힣A-Za-z]', '', page_text)
    return [t for t in missing if t.isdigit() or t not in letters]


def postprocess(key, page, raw):
    bands = BANDS.get(key)
    if not bands:
        return page
    pages = _pdf_pages()
    sections = []
    for pno, title, lines in bands:
        kept = []
        for line in lines:
            if pages is not None:
                missing = _missing(pages[pno - 1], line)
                if missing:
                    print(f'curr_fine: {key} p{pno} 원문에 없는 낱말 {missing[:5]} → 줄 버림: {line[:40]}', file=sys.stderr)
                    continue
            kept.append(line)
        if kept:
            sections.append({'title': title, 'items': kept, 'ordered': False})
    return {'title': TITLES.get(key, page.get('title', '')), 'sections': sections}
