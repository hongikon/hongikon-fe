def postprocess(key, page, raw):
    bands = BANDS.get(key)
    if not bands:
        return page
    pages = _pdf_pages()
    sections = []
    for pno, title, lines in bands:
        kept = []
        for line in lines:
            if pages is not None:
                missing = _verified(pages[pno - 1], line)
                if missing:
                    print(f'curr_archbiz: {key} p{pno} 원문에 없는 낱말 {missing[:5]} → 줄 버림: {line[:40]}', file=sys.stderr)
                    continue
            kept.append(line)
        if kept:
            sections.append({'title': title, 'items': kept, 'ordered': False})
    return {'title': TITLES.get(key, page.get('title', '')), 'sections': sections}
