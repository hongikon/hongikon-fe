def _flat(text):
    return re.sub(r'[\s*•]+', '', text)


def postprocess(key, page, raw):
    i = raw.find('fr-view')
    j = raw.find('이전글', i)
    body = _flat(html.unescape(re.sub(r'<[^>]+>', ' ', raw[i:j] if i >= 0 else raw)))
    kept = []
    for shown, parts in _RULES[key]:
        if all(_flat(p) in body for p in parts):
            kept.append(shown)
        else:
            print(f'deptrule_fine: {key} 원문에 없는 조각 → 줄 버림: {shown[:40]}', file=sys.stderr)
    return {'title': TITLES[key], 'sections': [{'title': SECTION[key], 'items': kept, 'ordered': False}] if kept else []}
