def _schedule_items():
    path = os.path.join(_ROOT, 'data', 'pages-schedule.json')
    if not os.path.exists(path):
        return [], None
    page = json.load(open(path, encoding='utf-8'))['pages'].get('schedule_year')
    if not page:
        return [], None
    year = int(re.search(r'(\d{4})학년도', page['title']).group(1))
    return [i for s in page['sections'] for i in s['items']], year


