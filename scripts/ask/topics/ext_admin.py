_DATE = r'(?:\d{4}\.)?\d{1,2}\.\d{1,2}\([월화수목금토일]\)|(?:\d{4}년 )?\d{1,2}월'


def _find(pattern):
    """일정 줄을 (날짜, 일정 이름)으로 나눠 이름이 pattern 에 맞는 첫 줄을 돌려준다.
    예: '8.26(수) ~ 8.27(목) 2026학년도 2학기 수강신청(전체학년)' → ('8.26(수) ~ 8.27(목)', '2026학년도 2학기 수강신청(전체학년)')."""
    for it in _ITEMS:
        m = re.match(rf'^((?:{_DATE})(?: ~ (?:{_DATE}))?) (.*)$', it)
        if m and re.search(pattern, m.group(2)):
            return m.group(1), m.group(2)
    return None


def _when(pattern):
    hit = _find(pattern)
    return hit[0] if hit else None


